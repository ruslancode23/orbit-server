-- A resend with the same client id returns the message already stored
-- instead of creating a second one (FR-04).
-- name: CreateMessage :one
INSERT INTO messages (channel_id, author_id, client_message_id, content, reply_to_id)
VALUES ($1, $2, $3, $4, $5)
ON CONFLICT (channel_id, author_id, client_message_id) WHERE author_id IS NOT NULL
    DO UPDATE SET channel_id = excluded.channel_id
-- xmax = 0 on a row this statement inserted; anything else means the resend
-- found the message already stored.
RETURNING *, (xmax = 0) AS inserted;

-- The author's public part comes from internal/profile in one batch per page:
-- this module never reads auth's table.
-- name: GetMessage :one
SELECT * FROM messages WHERE id = $1;

-- A system line is an ordinary message with kind = 'system': it takes a seq,
-- stays in history and has an author, but its text is generated by the server
-- and nobody may edit or delete it.
-- name: CreateSystemMessage :one
INSERT INTO messages (channel_id, author_id, client_message_id, content,
                      kind, system_type, system_target_id, system_name)
VALUES (sqlc.arg(channel_id), sqlc.arg(author_id), sqlc.arg(client_message_id),
        sqlc.arg(content), 'system', sqlc.arg(system_type),
        sqlc.narg(system_target_id), sqlc.narg(system_name))
RETURNING *;

-- One page of history, newest first: the caller passes the seq it already has
-- (NULL for the first page) and gets the next portion.
-- name: ListChannelMessages :many
SELECT *
FROM messages
WHERE messages.channel_id = $1
  AND (sqlc.narg(before_seq)::bigint IS NULL OR messages.seq < sqlc.narg(before_seq)::bigint)
ORDER BY messages.seq DESC
LIMIT $2;

-- name: EditMessage :one
UPDATE messages
SET content = $3, edited_at = now()
WHERE id = $1 AND author_id = $2 AND deleted_at IS NULL AND kind = 'user'
RETURNING *;

-- Soft delete: replies and read cursors keep pointing at the message.
-- name: DeleteMessage :one
UPDATE messages
SET deleted_at = now(), content = ''
WHERE id = $1 AND author_id = $2 AND deleted_at IS NULL AND kind = 'user'
RETURNING *;

-- name: AddMessageMention :exec
INSERT INTO message_mentions (message_id, user_id)
VALUES ($1, $2)
ON CONFLICT DO NOTHING;

-- name: ListMessageMentions :many
SELECT message_id, user_id FROM message_mentions
WHERE message_id = ANY($1::uuid[]);

-- name: AddReaction :exec
INSERT INTO message_reactions (message_id, user_id, emoji)
VALUES ($1, $2, $3)
ON CONFLICT DO NOTHING;

-- name: RemoveReaction :execrows
DELETE FROM message_reactions WHERE message_id = $1 AND user_id = $2 AND emoji = $3;

-- Reactions of a page of messages, with whether the caller is among them.
-- name: ListMessageReactions :many
SELECT message_id, emoji, count(*) AS total,
       bool_or(user_id = sqlc.arg(viewer_id)::uuid) AS reacted
FROM message_reactions
WHERE message_id = ANY(sqlc.arg(message_ids)::uuid[])
GROUP BY message_id, emoji
ORDER BY message_id, emoji;

-- What a reconnecting client missed in one channel, oldest first (task 2.6).
-- name: ListChannelMessagesAfter :many
SELECT *
FROM messages
WHERE messages.channel_id = $1 AND messages.seq > sqlc.arg(after_seq)
ORDER BY messages.seq
LIMIT $2;

-- The first message of a dialogue spends the same per-account rate-limit token
-- as opening one; this answers whether the dialogue has any message yet.
-- name: ChannelHasMessages :one
SELECT EXISTS (SELECT 1 FROM messages WHERE channel_id = $1);

-- name: SearchMessages :many
-- Full-text search (FEAT-6). The caller has already narrowed channel_ids to
-- what this account may read; this query only filters and orders the page.
-- Headline markers are control characters so message text cannot fake them.
SELECT messages.*,
       ts_headline(
           'russian',
           messages.content,
           websearch_to_tsquery('russian', sqlc.arg(term)::text)
               || websearch_to_tsquery('english', sqlc.arg(term)::text),
           'StartSel=' || chr(2) || ', StopSel=' || chr(3)
               || ', MaxWords=30, MinWords=8, MaxFragments=2, FragmentDelimiter= … '
       )::text AS headline
FROM messages
WHERE messages.channel_id = ANY(sqlc.arg(channel_ids)::uuid[])
  AND messages.deleted_at IS NULL
  AND messages.kind = 'user'
  AND messages.search @@ (
      websearch_to_tsquery('russian', sqlc.arg(term)::text)
          || websearch_to_tsquery('english', sqlc.arg(term)::text)
  )
  AND (sqlc.narg(author_id)::uuid IS NULL OR messages.author_id = sqlc.narg(author_id)::uuid)
  AND (sqlc.arg(has_files)::boolean = false
       OR EXISTS (SELECT 1 FROM attachments WHERE attachments.message_id = messages.id))
  AND (sqlc.narg(before)::bigint IS NULL OR messages.seq < sqlc.narg(before)::bigint)
  AND (coalesce(cardinality(sqlc.arg(excluded_authors)::uuid[]), 0) = 0
       OR messages.author_id IS NULL
       OR NOT (messages.author_id = ANY(sqlc.arg(excluded_authors)::uuid[])))
ORDER BY messages.seq DESC
LIMIT sqlc.arg(page_limit)::int;
